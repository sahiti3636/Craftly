# Blur check (step 1) — real pipeline, using the fixtures
# ---------------------------------------------------------------------------


def test_blurry_image_stops_pipeline_with_retake_warning(tmp_path):
    result = clean_product_image(FIXTURES_DIR / "blurry.jpg", output_dir=tmp_path)
    assert result == {"clean_path": None, "alpha_path": None, "warnings": ["retake"]}
    assert list(tmp_path.iterdir()) == []  # nothing written


def test_dark_but_sharp_image_is_not_falsely_flagged_as_blurry(tmp_path):
    # Regression test: naive variance-of-Laplacian on the raw (unequalized)
    # image would flag this as blurry purely because it's dark, not
    # because it's actually out of focus. See _blur_score's docstring.
    result = clean_product_image(FIXTURES_DIR / "dark.jpg", output_dir=tmp_path)
    assert "retake" not in result["warnings"]
    assert result["clean_path"] is not None


def test_blur_score_ranks_blurry_below_sharp_images():
    scores = {}
    for name in ("blurry", "dark", "cluttered", "off_white", "tight_crop"):
        bgr = cv2.imread(str(FIXTURES_DIR / f"{name}.jpg"))
        gray = cv2.cvtColor(bgr, cv2.COLOR_BGR2GRAY)
        scores[name] = image_module._blur_score(gray)

    assert scores["blurry"] < image_module.BLUR_THRESHOLD
    for name in ("dark", "cluttered", "off_white", "tight_crop"):
        assert scores[name] > scores["blurry"]
        assert scores[name] >= image_module.BLUR_THRESHOLD


