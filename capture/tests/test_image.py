"""Tests for app/image.py.

Two testing strategies, mirroring the pattern used elsewhere in this
project (mock the heavy/nondeterministic boundary, exercise the
deterministic logic directly):

- A handful of tests run the REAL rembg pipeline end-to-end against the
  5 deliberately-bad fixtures in tests/fixtures/bad_photos/ (generated by
  scripts/generate_bad_test_images.py), using the lightweight u2netp
  model (see conftest.py) for speed. These catch real integration bugs —
  in fact, they're exactly how the white-balance/cyan-background bug
  documented in _gray_world_white_balance's docstring was found.
- Most tests mock app.image._remove_background to return a controlled
  RGBA cutout, so cropping/padding/white-balance/output-spec logic can be
  tested precisely and fast, without depending on what a real ML model
  happens to segment.
"""

from pathlib import Path

import cv2
import numpy as np
import pytest
from PIL import Image

import app.image as image_module
from app.image import clean_product_image, thumbnail_path_for

FIXTURES_DIR = Path(__file__).resolve().parent / "fixtures" / "bad_photos"


# ---------------------------------------------------------------------------
# helpers for the mocked-background-removal tests
# ---------------------------------------------------------------------------


def _make_source_photo(path: Path, size: int = 400, bg=(240, 240, 240), fg=(150, 60, 40)):
    """A simple sharp product-on-background photo, saved to `path`."""
    from PIL import ImageDraw

    img = Image.new("RGB", (size, size), bg)
    draw = ImageDraw.Draw(img)
    margin = size // 4
    draw.ellipse([margin, margin, size - margin, size - margin], fill=fg)
    img.save(path, quality=95)
    return path


def _make_rgba_cutout(size: int = 400, fg=(150, 60, 40), circle_frac: float = 0.5) -> Image.Image:
    """A synthetic RGBA "background-removed" result: an opaque circle on
    a transparent field, standing in for whatever rembg would produce.
    """
    rgba = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    from PIL import ImageDraw

    draw = ImageDraw.Draw(rgba)
    r = size * circle_frac / 2
    cx, cy = size // 2, size // 2
    draw.ellipse([cx - r, cy - r, cx + r, cy + r], fill=(*fg, 255))
    return rgba


@pytest.fixture
def mock_background_removal(monkeypatch):
    """Returns a setter: call it with an RGBA image to control exactly
    what `clean_product_image` sees from background removal.
    """

    def _set(rgba: Image.Image):
        monkeypatch.setattr(image_module, "_remove_background", lambda pil_rgb: rgba)

    return _set


def _corner_pixel(clean_path: str) -> tuple[int, int, int]:
    img = Image.open(clean_path).convert("RGB")
    return img.getpixel((2, 2))


