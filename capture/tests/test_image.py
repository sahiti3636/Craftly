def test_rembg_model_is_configurable_via_env_var(monkeypatch):
    monkeypatch.setattr(image_module, "REMBG_MODEL", "some-other-model")
    monkeypatch.setattr(image_module, "_session", None)

    captured = {}

    def fake_new_session(model_name):
        captured["model_name"] = model_name
        return "fake-session"

    monkeypatch.setattr("rembg.new_session", fake_new_session)

    session = image_module._get_rembg_session()
    assert session == "fake-session"
    assert captured["model_name"] == "some-other-model"


def test_default_rembg_model_is_not_rembgs_own_default():
    # rembg's own new_session() default is "bria-rmbg" (confirmed by
    # inspecting its signature — see app/image.py's module docstring),
    # which requires a paid commercial licence. This module must never
    # rely on that default.
    #
    # Checked against the literal fallback in the source (not
    # image_module.REMBG_MODEL, which tests/conftest.py deliberately
    # overrides to the lightweight u2netp for test speed) — this test is
    # about what a deployment with no CRAFTLY_REMBG_MODEL set would get.
    import inspect

    from rembg import new_session

    rembg_own_default = inspect.signature(new_session).parameters["model_name"].default

    source = Path(image_module.__file__).read_text()
    assert 'os.environ.get("CRAFTLY_REMBG_MODEL", "u2net")' in source
    assert rembg_own_default != "u2net"


